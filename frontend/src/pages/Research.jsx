import React, { useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { postJson } from '../api'
import { Card, DataTable, Empty, Page, SafetyBanner, Tag } from '../components'

// The research screen's job is to make the difference between an AI suggestion
// and a sourced fact impossible to miss. Every factual field shows its
// provenance, and unavailable fields are displayed rather than hidden — an
// empty column here means "nobody could tell us", which is information.

function ProvenanceTag({ provenance }) {
  const cls = provenance === 'SOURCED' ? 'ok'
    : provenance === 'AI_INFERENCE' ? 'REQUIRES_REVIEW' : 'NOT_SUPPORTED'
  return <span className={`tag ${cls}`}>{provenance}</span>
}

export default function Research() {
  const [query, setQuery] = useState('hair trimmers and steel lunchboxes under 500')
  const [run, setRun] = useState(null)
  const [status, setStatus] = useState(null)
  const [busy, setBusy] = useState(false)
  const [expanded, setExpanded] = useState(null)
  const navigate = useNavigate()

  async function search() {
    setBusy(true); setStatus('Researching — asking for hypotheses, then checking sources…'); setRun(null)
    try {
      const result = await postJson('/api/research', { query })
      setRun(result)
      setStatus(result.status === 'DEGRADED'
        ? 'Completed in degraded mode — no research model is configured.'
        : `Completed. ${result.candidates.length} candidate(s).`)
    } catch (e) {
      setStatus(`Failed: ${e.detail ?? e.message}`)
    } finally { setBusy(false) }
  }

  async function sendToAnalysis() {
    setBusy(true); setStatus('Writing sourced observations and rebuilding the pipeline…')
    try {
      const result = await postJson(`/api/research/${run.id}/send-to-analysis`, { persist: true })
      setStatus(`Wrote ${result.written.observations} observation(s). ${result.note}`)
      setTimeout(() => navigate('/opportunities'), 1500)
    } catch (e) {
      setStatus(`Failed: ${e.detail ?? e.message}`)
    } finally { setBusy(false) }
  }

  return (
    <Page title="AI Research" subtitle="The model suggests what to investigate. Sources supply the facts.">
      <SafetyBanner />

      <div className="card" style={{ marginBottom: 18 }}>
        <div className="label">Research request</div>
        <div style={{ display: 'flex', gap: 10, marginTop: 8 }}>
          <input
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={(e) => e.key === 'Enter' && !busy && search()}
            placeholder="e.g. hair trimmers under 500 supplier cost"
            style={{ flex: 1, background: '#0f1115', color: 'var(--ink)',
              border: '1px solid var(--line)', borderRadius: 5, padding: '8px 10px' }}
          />
          <button disabled={busy || query.trim().length < 3} onClick={search}>
            {busy ? 'Working…' : 'Research'}
          </button>
        </div>
        <div className="note" style={{ marginTop: 8 }}>
          No price, cost, MOQ, GST, demand or supplier figure is ever generated by
          the model. Those come from a source or stay UNAVAILABLE.
        </div>
      </div>

      {status && <div className="banner">{status}</div>}

      {run && (
        <>
          <div className="cards">
            <Card label="Candidates" value={run.candidates.length} note="AI suggestions" />
            <Card label="Research model" value={run.ai_available ? 'available' : 'not configured'}
              note={run.ai_error ? String(run.ai_error).slice(0, 60) : 'degrades to your own terms'} />
            <Card label="Sources reachable"
              value={`${run.sources.filter((s) => s.available).length}/${run.sources.length}`}
              note="the rest yield UNAVAILABLE" />
            <Card label="Status" value={run.status} />
          </div>

          {run.warnings.length > 0 && (
            <>
              <h2>What the assistant could not do</h2>
              <ul className="reasons">{run.warnings.map((w, i) => <li key={i}>{w}</li>)}</ul>
            </>
          )}

          <h2>Candidates</h2>
          {run.candidates.length === 0 ? <Empty>No candidates. See the warnings above.</Empty> : (
            <>
              <DataTable
                columns={[
                  { key: 'name', label: 'Product', render: (r) => (
                    <a href="#detail" onClick={(e) => { e.preventDefault(); setExpanded(expanded === r.id ? null : r.id) }}>
                      {r.name}
                    </a>) },
                  { key: 'category', label: 'Category' },
                  { key: 'origin', label: 'Origin', render: () => <Tag value="REQUIRES_REVIEW" /> },
                  { key: 'ai_confidence', label: 'AI confidence' },
                  { key: 'sourced', label: 'Sourced facts', align: 'right',
                    render: (r) => r.provenance_summary.sourced.length },
                  { key: 'unavail', label: 'Unavailable', align: 'right',
                    render: (r) => r.provenance_summary.unavailable.length },
                  { key: 'evidence', label: 'Evidence', align: 'right',
                    render: (r) => `${r.provenance_summary.evidence_pct}%` },
                ]}
                rows={run.candidates.map((c) => ({ ...c, id: c.id }))}
              />
              <p className="muted small" style={{ marginTop: 8 }}>
                Origin is always an AI suggestion. Only the sourced fields are evidence.
                Click a product to see every claim and its source.
              </p>
            </>
          )}

          {expanded && (() => {
            const c = run.candidates.find((x) => x.id === expanded)
            return (
              <div id="detail">
                <h2>{c.name} — every claim</h2>
                <p className="muted small">{c.rationale}</p>
                <DataTable
                  columns={[
                    { key: 'field', label: 'Field' },
                    { key: 'provenance', label: 'Provenance', render: (r) => <ProvenanceTag provenance={r.provenance} /> },
                    { key: 'value', label: 'Value', render: (r) => r.value ?? <span className="muted">—</span> },
                    { key: 'reference', label: 'Source', render: (r) => (
                      <span className="small muted">{r.reference ?? r.note ?? '—'}</span>) },
                    { key: 'observed_at', label: 'Observed', render: (r) => (
                      <span className="small muted">{r.observed_at ? r.observed_at.slice(0, 10) : '—'}</span>) },
                    { key: 'confidence', label: 'Confidence' },
                  ]}
                  rows={c.claims.map((x, i) => ({ ...x, id: i }))}
                />
              </div>
            )
          })()}

          {run.candidates.length > 0 && (
            <>
              <h2>Would be written to observations.csv</h2>
              <pre>{run.export_preview['observations.csv']}</pre>
              <p className="muted small">
                Blank columns are facts no source could supply. They are written blank
                so the ingester records them as UNKNOWN rather than defaulting them.
                Supplier rows are never written from research.
              </p>
              <div style={{ marginTop: 14 }}>
                <button disabled={busy} onClick={sendToAnalysis}>Send to Analysis</button>
                <span className="muted small" style={{ marginLeft: 12 }}>
                  Adds these to discovery. The RECOMMENDED / BACKUP / REJECTED verdict is
                  decided by the existing economics, compliance and opportunity engines —
                  not by the research model. Human approval is still required before anything executes.
                </span>
              </div>
            </>
          )}
        </>
      )}
    </Page>
  )
}
